"""Size classifier on the measured diff (FR-52), its class-gaming rule (FR-69), and the per-slice
PR soft cap (D-15).

    measure(top, remote, base, cfg) -> {"files": {class: n}, "lines": {class: n}, "cap": n, "over_cap": bool}
                                       or None when the diff cannot be measured

Classes: handwritten, generated_or_mechanical, tests, docs, sensitive. Precedence, highest first:
sensitive > generated > tests > docs > handwritten, so a label can only move a file toward
scrutiny between those, never below `sensitive`.

CLASS GAMING (FR-69), deliberately STRICTER than the other test-path helpers in this repo (do not
"unify" them): the tests class needs a TEST PATH and the generated class needs a configured glob
(`work.generated_globs`) or a header marker in the first lines of the file at HEAD. File content
never decides a class otherwise; anything else is handwritten. A header marker does let a hand-edited
file claim `generated`, so the fail-closed small-goal net (FR-55, a later slice) must not rely on
this classifier alone.

The soft cap counts handwritten + sensitive lines (not generated, tests or docs), default 400
(`work.slice_pr_soft_cap`, D-15's proposed value pending the baseline), strictly greater-than, and is
ADVISORY: `work.pr` appends a note, nothing refuses. Sensitive globs are risk-detect.sh's defaults
(its `.sdlc/**` and `docs/**` exclusions included); `.sdlc/risk-detect.conf` overrides are not read,
because reading them needs a shell opt-in.

COST: two git processes for the numstat and merge-base, plus at most two for the header reads
(`cat-file --batch-check`, then `--batch`), whatever the diff size. Header reads are bounded to
MAX_HEADER_FILES files of at most MAX_HEADER_BYTES each (only HEADER_LINES lines are used); a file
past either bound has no header and is handwritten. Every git call has a timeout. Binary files count
as files, with 0 lines. A renamed file is classified by its NEW path.
"""
import fnmatch
import os
import subprocess

CLASSES = ("handwritten", "generated_or_mechanical", "tests", "docs", "sensitive")
DEFAULT_CAP = 400
MAX_HEADER_FILES = 500
MAX_HEADER_BYTES = 65536
HEADER_LINES = 5
GIT_TIMEOUT = 30

#: risk-detect.sh's SENSITIVE_GLOBS default, pinned equal by tests/test_size_class.py.
SENSITIVE_GLOBS = ("*auth*", "*login*", "*session*", "*permission*", "*rbac*", "*payment*", "*billing*",
                   ".env*", "*.env", "*/.env*", "*secret*", "*credential*")
_MARKERS = ("@generated", "do not edit", "code generated", "auto-generated", "autogenerated")
_TEST_DIRS = {"tests", "test", "__tests__", "spec"}
_DOC_SUFFIXES = (".md", ".rst", ".txt")


def _match(path, globs):
    return any(fnmatch.fnmatchcase(path, g) for g in globs)       # `*` crosses `/`, like a bash case glob


def _is_test_path(path):
    parts = path.split("/")
    name = parts[-1]
    return (any(p in _TEST_DIRS for p in parts[:-1]) or name.startswith("test_")
            or any(fnmatch.fnmatchcase(name, g) for g in ("*_test.*", "*.test.*", "*.spec.*")))


def classify_file(path, generated_globs=(), header=""):
    """The class of one changed file. `header` is the file's first lines at HEAD, "" when unknown."""
    if not path.startswith((".sdlc/", "docs/")) and _match(path, SENSITIVE_GLOBS):
        return "sensitive"
    if _match(path, generated_globs) or any(m in header.lower() for m in _MARKERS):
        return "generated_or_mechanical"
    if _is_test_path(path):
        return "tests"
    if path.startswith(".sdlc/") or path.endswith(_DOC_SUFFIXES):
        return "docs"
    return "handwritten"


def classify_files(files, generated_globs=(), headers=None):
    """files: [(path, lines | "binary")]; headers: {path: first lines}. Counts for every class."""
    out = {"files": {c: 0 for c in CLASSES}, "lines": {c: 0 for c in CLASSES}}
    for path, n in files:
        cls = classify_file(path, generated_globs, (headers or {}).get(path, ""))
        out["files"][cls] += 1
        out["lines"][cls] += n if isinstance(n, int) else 0
    return out


def _git(top, args, stdin=None):
    """stdout bytes of one git call, or None on any failure or timeout."""
    try:
        p = subprocess.run(["git", "-C", str(top), "--no-optional-locks", *args], input=stdin,
                           capture_output=True, timeout=GIT_TIMEOUT)
    except (OSError, subprocess.SubprocessError):
        return None
    return p.stdout if p.returncode == 0 else None


def _numstat(top, fork):
    """[(path, added+deleted | "binary")] for fork..HEAD, a rename keyed on its NEW path; None on failure."""
    raw = _git(top, ["-c", "diff.renames=true", "diff", "--numstat", "-z", "-M", "--no-textconv",
                     "--no-ext-diff", fork, "HEAD"])
    if raw is None:
        return None
    items, i, found = os.fsdecode(raw).split("\0"), 0, []
    while i < len(items) and items[i]:
        parts = items[i].split("\t", 2)
        i += 1
        if len(parts) != 3:
            return None
        added, deleted, path = parts
        if path == "":                                  # rename: `A\tD\t\0old\0new\0`
            if i + 1 >= len(items):
                return None
            path, i = items[i + 1], i + 2
        if added == "-" and deleted == "-":
            found.append((path, "binary"))
        elif added.isdigit() and deleted.isdigit():
            found.append((path, int(added) + int(deleted)))
        else:
            return None
    return found


def _headers(top, paths):
    """{path: first HEADER_LINES lines at HEAD} for the first MAX_HEADER_FILES paths whose blob is
    present and at most MAX_HEADER_BYTES; every other path is simply absent (-> no header)."""
    paths = [p for p in paths if "\n" not in p][:MAX_HEADER_FILES]
    if not paths:
        return {}
    checked = _git(top, ["cat-file", "--batch-check"], "".join("HEAD:%s\n" % p for p in paths).encode("utf-8", "surrogateescape"))
    if checked is None:
        return {}
    small = []
    for path, line in zip(paths, os.fsdecode(checked).split("\n")):
        f = line.split(" ")
        if len(f) == 3 and f[1] == "blob" and f[2].isdigit() and int(f[2]) <= MAX_HEADER_BYTES:
            small.append(path)
    blobs = _git(top, ["cat-file", "--batch"], "".join("HEAD:%s\n" % p for p in small).encode("utf-8", "surrogateescape")) if small else b""
    out, pos = {}, 0
    try:
        for path in small if blobs is not None else ():
            end = blobs.find(b"\n", pos)
            size = int(blobs[pos:end].split(b" ")[2])
            out[path] = b"\n".join(blobs[end + 1:end + 1 + size].split(b"\n")[:HEADER_LINES]).decode("utf-8", "replace")
            pos = end + 1 + size + 1
    except (ValueError, IndexError):                    # a blob vanished between the two calls: no headers
        return {}
    return out


def _cap(cfg):
    value = ((cfg or {}).get("work") or {}).get("slice_pr_soft_cap")
    return value if type(value) is int and value > 0 else DEFAULT_CAP


def measure(top, remote, base, cfg=None):
    """Classify fork..HEAD of the checkout at `top`; None when anything cannot be measured."""
    fork = _git(top, ["merge-base", "HEAD", "%s/%s" % (remote, base)])
    files = _numstat(top, fork.decode().strip()) if fork and fork.strip() else None
    if files is None:
        return None
    globs = ((cfg or {}).get("work") or {}).get("generated_globs")
    globs = tuple(g for g in globs if isinstance(g, str)) if isinstance(globs, list) else ()
    out = classify_files(files, globs, _headers(top, [p for p, _n in files if not _match(p, globs)]))
    cap = _cap(cfg)
    out["cap"] = cap
    out["over_cap"] = out["lines"]["handwritten"] + out["lines"]["sensitive"] > cap
    return out


def soft_cap_note(size):
    """The advisory line for an over-cap measurement, "" otherwise."""
    if not size or not size.get("over_cap"):
        return ""
    n = size["lines"]["handwritten"] + size["lines"]["sensitive"]
    return (" (soft cap: %d handwritten+sensitive lines exceed the per-slice PR cap of %d; advisory, "
            "split the slice or say why in the PR)" % (n, size["cap"]))
