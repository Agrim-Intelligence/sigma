#!/usr/bin/env python3
"""Keep the navigation block identical on every page of the docs site (`site/`).

LIBRARY TOOL: a maintainer's helper, not a skill script. It is not installed with the plugin and
nothing at run time calls it. The site has no build step, so each page carries its own copy of the
sidebar between two marker comments; this tool is the single source of that copy.

    python3 tools/site_nav.py check [site-dir]   exit 1 if any page's nav differs from the canonical one
    python3 tools/site_nav.py write [site-dir]   rewrite every page's nav; create a stub for a page that is missing

The page list is `PAGES` below. To add a page: add a row, run `write`, fill in the stub.
The nav marks the page's own link `class="active"`; `check` compares the whole block, so a page
that marks the wrong link (or none) fails too. Standard library only. Writes only under the
site directory; `check` writes nothing.
"""
from __future__ import annotations

import html
import sys
from pathlib import Path

START = "<!-- NAV:START (generated by tools/site_nav.py; do not edit by hand) -->"
END = "<!-- NAV:END -->"

# (file, title, group). Order is the nav order and the numbering.
GROUPS = [
    ("Start here", [
        ("index.html", "Home"),
        ("get-started.html", "Get started"),
        ("flow.html", "How it works"),
        ("entry-points.html", "Ways in"),
        ("design-gate.html", "The design gate"),
    ]),
    ("Set up & run", [
        ("setup.html", "Setup"),
        ("hosts.html", "Hosts"),
        ("config.html", "Configuration"),
        ("sdlc-folder.html", "The .sdlc folder"),
        ("run.html", "Running unattended"),
        ("orchestrate.html", "Running many goals"),
        ("cloud.html", "Cloud sessions"),
        ("observe.html", "Cost and time"),
    ]),
    ("Ways to work", [
        ("solo.html", "On your own"),
        ("team.html", "As a team"),
        ("slack.html", "From Slack"),
    ]),
    ("Deeper", [
        ("skills.html", "Skills and commands"),
        ("labels.html", "Labels"),
        ("units.html", "Units of work"),
        ("safety.html", "Trust and limits"),
        ("reference.html", "Technical reference"),
    ]),
    ("Reference", [
        ("releases.html", "Releases"),
        ("glossary.html", "Glossary"),
    ]),
]

PAGES = [(f, t, g) for g, items in GROUPS for f, t in items]
TITLES = {f: t for f, t, _ in PAGES}
GROUP_OF = {f: g for f, _, g in PAGES}

FAVICON = ("data:image/svg+xml,%3Csvg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 100 100'%3E"
           "%3Ctext y='.85em' font-size='90' font-family='sans-serif'%3E%CE%A3%3C/text%3E%3C/svg%3E")


def nav_block(active: str) -> str:
    """The canonical nav for the page `active` (a file name from PAGES)."""
    out = [START, '<nav class="sidebar">',
           '  <a class="brand" href="index.html">',
           '    <span class="brand-mark">&Sigma;</span>',
           '    <span><span class="brand-name">Sigma Loop</span><span class="brand-tag">Guide</span></span>',
           '  </a>',
           '  <details class="navbox" open>',
           '    <summary>Menu</summary>']
    n = 0
    for group, items in GROUPS:
        out.append('  <div class="nav-group">')
        out.append(f'    <div class="nav-group-title">{html.escape(group, quote=False)}</div>')
        for f, t in items:
            n += 1
            cls = ' class="active"' if f == active else ""
            cur = ' aria-current="page"' if f == active else ""
            out.append(f'    <a href="{f}"{cls}{cur}><span class="nav-num">{n:02d}</span>'
                       f'{html.escape(t, quote=False)}</a>')
        out.append("  </div>")
    out += ["  </details>",
            "  <script>(function(){var d=document.querySelector('.navbox'),m=window.matchMedia('(min-width: 901px)');"
            "function s(){d.open=m.matches}s();m.addEventListener('change',s);d.addEventListener('toggle',function(){var a=d.querySelector('.active');if(d.open&&a&&!m.matches)a.scrollIntoView({block:'center'})})})()</script>",
            "</nav>", END]
    return "\n".join(out)


def stub(f: str) -> str:
    title = TITLES[f]
    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Sigma Loop: {html.escape(title, quote=False)}</title>
<link rel="icon" href="{FAVICON}">
<link rel="stylesheet" href="assets/style.css">
</head>
<body>
<div class="layout">

{nav_block(f)}

<main>

<span class="eyebrow">{html.escape(GROUP_OF[f], quote=False)}</span>
<h1>{html.escape(title, quote=False)}</h1>
<p class="stub">Content in progress.</p>

</main>
</div>
</body>
</html>
"""


def _split(text: str):
    """(before, block, after) around the marker pair, or None when the markers are missing."""
    i = text.find(START)
    j = text.find(END)
    if i < 0 or j < 0 or j < i:
        return None
    j += len(END)
    return text[:i], text[i:j], text[j:]


def check(site: Path) -> list[str]:
    problems = []
    on_disk = {p.name for p in site.glob("*.html")}
    for f in sorted(on_disk - set(TITLES)):
        problems.append(f"{f}: page is not listed in PAGES (add it to tools/site_nav.py)")
    for f, _, _ in PAGES:
        p = site / f
        if not p.exists():
            problems.append(f"{f}: listed in PAGES but missing (run: python3 tools/site_nav.py write)")
            continue
        parts = _split(p.read_text(encoding="utf-8"))
        if parts is None:
            problems.append(f"{f}: nav markers missing")
        elif parts[1] != nav_block(f):
            problems.append(f"{f}: nav differs from the canonical one (run: python3 tools/site_nav.py write)")
    return problems


def write(site: Path) -> list[str]:
    changed = []
    site.mkdir(parents=True, exist_ok=True)
    for f, _, _ in PAGES:
        p = site / f
        if not p.exists():
            p.write_text(stub(f), encoding="utf-8")
            changed.append(f"{f}: created")
            continue
        text = p.read_text(encoding="utf-8")
        parts = _split(text)
        if parts is None:
            changed.append(f"{f}: NO nav markers; left untouched")
            continue
        new = parts[0] + nav_block(f) + parts[2]
        if new != text:
            p.write_text(new, encoding="utf-8")
            changed.append(f"{f}: nav rewritten")
    return changed


def main(argv: list[str]) -> int:
    if not argv or argv[0] in ("-h", "--help") or argv[0] not in ("check", "write"):
        print(__doc__.strip().split("\n\n")[0])
        print("usage: site_nav.py check|write [site-dir]")
        return 0 if argv and argv[0] in ("-h", "--help") else 2
    default = Path(__file__).resolve().parent.parent / "site"
    site = Path(argv[1]) if len(argv) > 1 else default
    if argv[0] == "check":
        problems = check(site)
        for line in problems:
            print(line)
        print("site nav: ok" if not problems else f"site nav: {len(problems)} problem(s)")
        return 1 if problems else 0
    changed = write(site)
    for line in changed:
        print(line)
    return 1 if any("NO nav markers" in c for c in changed) else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
