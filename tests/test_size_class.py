"""#2004 (lean goals slice 9): the size classifier (FR-52), its class-gaming rule (FR-69) and the
per-slice PR soft cap (D-15). Real git for `measure`; the `pr()` hook runs against a fake `run`.

Every guard here was broken alone and seen red (the clauses are listed in `.sdlc/plans/2004.md`).
FR-69 is deliberately STRICTER than the repo's other test-path helpers: a test class needs a test
PATH, a generated class needs a configured glob or a header marker, and content never decides.
"""
