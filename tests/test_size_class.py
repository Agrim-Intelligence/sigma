ROOT = pathlib.Path(__file__).resolve().parent.parent
SCRIPTS = ROOT / "skills" / "sigma-loop" / "scripts"


def _load(name):
    spec = importlib.util.spec_from_file_location(name, SCRIPTS / f"{name}.py")
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


sc = _load("size_class")
work = _load("work")


def test_a_test_looking_file_outside_a_test_path_is_handwritten():
    # content never decides: only the path can put a file in the tests class (FR-69)
    assert sc.classify_file("src/app.py", header="def test_x():\n    assert 1\n") == "handwritten"
    assert sc.classify_file("src/helpers.py") == "handwritten"
    assert sc.classify_file("tests/test_app.py") == "tests"
    assert sc.classify_file("pkg/__tests__/a.js") == "tests"
    assert sc.classify_file("pkg/a.spec.ts") == "tests"
    assert sc.classify_file("pkg/a_test.go") == "tests"


def test_a_generated_looking_name_without_glob_or_marker_is_handwritten():
    assert sc.classify_file("src/schema_generated.py") == "handwritten"
    assert sc.classify_file("src/gen/api.py", header="import os\n") == "handwritten"


def test_marker_or_configured_glob_makes_generated():
    g = "generated_or_mechanical"
    assert sc.classify_file("src/api.py", header="# Code generated by protoc. DO NOT EDIT.\n") == g
    assert sc.classify_file("src/api.py", header="// @generated\n") == g
    assert sc.classify_file("src/gen/api.py", generated_globs=("src/gen/*",)) == g
    assert sc.classify_file("src/other.py", generated_globs=("src/gen/*",)) == "handwritten"


def test_precedence_sensitive_first():
    # a gamed label must never lower scrutiny below sensitive
    assert sc.classify_file("src/auth.py") == "sensitive"
    assert sc.classify_file("tests/test_auth.py") == "sensitive"
    assert sc.classify_file("src/auth_pb.py", header="@generated\n") == "sensitive"
    assert sc.classify_file("tests/gen_tests.py", header="@generated\n") == "generated_or_mechanical"
    assert sc.classify_file("tests/test_a.py") == "tests"
    assert sc.classify_file("README.md") == "docs"
    assert sc.classify_file("notes/a.rst") == "docs"
    assert sc.classify_file("docs/guide.py") == "handwritten"      # a directory name alone is not docs


def test_docs_and_sdlc_paths_are_never_sensitive():
    # risk-detect.sh excludes .sdlc/** and docs/**; `*auth*` also matches "author"
    assert sc.classify_file("docs/session-notes.md") == "docs"
    assert sc.classify_file(".sdlc/plans/author.md") == "docs"
    assert sc.classify_file(".sdlc/state/x.json") == "docs"


def test_sensitive_globs_match_risk_detect():
    text = (SCRIPTS / "risk-detect.sh").read_text(encoding="utf-8")
    line = re.search(r"^SENSITIVE_GLOBS='([^']*)'", text, re.M).group(1).split()
    assert list(sc.SENSITIVE_GLOBS) == line


def test_counts_every_class_key_and_binary_counts_files_not_lines():
    out = sc.classify_files([("src/a.py", 10), ("tests/test_a.py", 20), ("logo.png", "binary"),
                             ("README.md", 3), ("src/auth.py", 5)])
    assert set(out["files"]) == set(sc.CLASSES) == set(out["lines"])
    assert out["files"] == {"handwritten": 2, "generated_or_mechanical": 0, "tests": 1, "docs": 1,
                            "sensitive": 1}
    assert out["lines"] == {"handwritten": 10, "generated_or_mechanical": 0, "tests": 20, "docs": 3,
                            "sensitive": 5}


# --- measure: real git ---------------------------------------------------------------------------

def _git(cwd, *args):
    subprocess.run(["git", "-C", str(cwd), *args], check=True, capture_output=True, text=True,
                   env={"GIT_AUTHOR_NAME": "t", "GIT_AUTHOR_EMAIL": "t@t", "GIT_COMMITTER_NAME": "t",
                        "GIT_COMMITTER_EMAIL": "t@t", "PATH": "/usr/bin:/bin:/usr/local/bin:/opt/homebrew/bin",
                        "HOME": str(cwd)})


def _repo(tmp_path, base_files):
    origin, top = tmp_path / "origin.git", tmp_path / "top"
    origin.mkdir()
    top.mkdir()
    _git(origin, "init", "--bare", "-b", "main")
    _git(top, "init", "-b", "main")
    _git(top, "remote", "add", "origin", str(origin))
    _write(top, base_files)
    _git(top, "add", "-A")
    _git(top, "commit", "-m", "base")
    _git(top, "push", "origin", "main")
    _git(top, "checkout", "-b", "sdlc/x")
    return top


def _write(top, files):
    for rel, body in files.items():
        p = top / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(body)


def _commit(top, files=None, remove=(), move=()):
    _write(top, files or {})
    for rel in remove:
        (top / rel).unlink()
    for a, b in move:
        (top / b).parent.mkdir(parents=True, exist_ok=True)
        (top / a).rename(top / b)
    _git(top, "add", "-A")
    _git(top, "commit", "-m", "work")


def test_measure_on_a_real_branch(tmp_path):
    top = _repo(tmp_path, {"seed.txt": "x\n"})
    _commit(top, {"src/a.py": "a\n" * 7, "tests/test_a.py": "t\n" * 4, "docs/g.md": "d\n" * 2,
                  "src/api.py": "# @generated\n" + "g\n" * 9, "src/auth.py": "s\n" * 3,
                  "gen/x.py": "g\n" * 6})
    out = sc.measure(str(top), "origin", "main", {"work": {"generated_globs": ["gen/*"]}})
    assert out["files"] == {"handwritten": 1, "generated_or_mechanical": 2, "tests": 1, "docs": 1,
                            "sensitive": 1}
    assert out["lines"] == {"handwritten": 7, "generated_or_mechanical": 16, "tests": 4, "docs": 2,
                            "sensitive": 3}
    assert out["cap"] == 400 and out["over_cap"] is False


def test_measure_is_none_when_nothing_can_be_measured(tmp_path):
    assert sc.measure(str(tmp_path), "origin", "main", {}) is None            # not a git checkout
    assert sc.measure(str(tmp_path / "missing"), "origin", "main", {}) is None


def test_soft_cap_is_strictly_over_and_counts_handwritten_and_sensitive(tmp_path):
    top = _repo(tmp_path, {"seed.txt": "x\n"})
    _commit(top, {"src/a.py": "a\n" * 7, "src/auth.py": "s\n" * 3, "tests/test_a.py": "t\n" * 50,
                  "docs/g.md": "d\n" * 50, "gen/x.py": "g\n" * 50})
    cfg = {"work": {"generated_globs": ["gen/*"], "slice_pr_soft_cap": 10}}
    at = sc.measure(str(top), "origin", "main", cfg)
    assert at["cap"] == 10 and at["over_cap"] is False                       # 7 + 3 == cap: not over
    cfg["work"]["slice_pr_soft_cap"] = 9
    over = sc.measure(str(top), "origin", "main", cfg)
    assert over["over_cap"] is True
    assert "10" in sc.soft_cap_note(over) and "9" in sc.soft_cap_note(over)
    assert sc.soft_cap_note(at) == ""
    assert sc.soft_cap_note(None) == ""


@pytest.mark.parametrize("bad", [True, False, 0, -5, "400", 1.5, None, [3]])
def test_bad_cap_values_read_as_the_default(tmp_path, bad):
    top = _repo(tmp_path, {"seed.txt": "x\n"})
    _commit(top, {"src/a.py": "a\n"})
    assert sc.measure(str(top), "origin", "main", {"work": {"slice_pr_soft_cap": bad}})["cap"] == 400


def test_a_rename_is_classified_by_its_new_path(tmp_path):
    body = "line\n" * 5
    top = _repo(tmp_path, {"tests/x.py": body, "seed.txt": "x\n"})
    _commit(top, move=[("tests/x.py", "src/x.py")])
    out = sc.measure(str(top), "origin", "main", {})
    assert out["files"]["handwritten"] == 1 and out["files"]["tests"] == 0, out


def test_a_deleted_file_has_no_header_and_is_handwritten(tmp_path):
    top = _repo(tmp_path, {"src/api.py": "# @generated\n" + "g\n" * 4, "seed.txt": "x\n"})
    _commit(top, remove=["src/api.py"])
    out = sc.measure(str(top), "origin", "main", {})
    assert out["files"]["handwritten"] == 1 and out["files"]["generated_or_mechanical"] == 0, out
    assert out["lines"]["handwritten"] == 5


def test_header_reads_are_bounded(tmp_path):
    # past the byte bound a marker is never read (the blob is not loaded) -> handwritten
    top = _repo(tmp_path, {"seed.txt": "x\n"})
    big = "# @generated\n" + "x" * (sc.MAX_HEADER_BYTES + 10) + "\n"
    _commit(top, {"src/big.py": big, "src/small.py": "# @generated\nx\n"})
    out = sc.measure(str(top), "origin", "main", {})
    assert out["files"]["handwritten"] == 1 and out["files"]["generated_or_mechanical"] == 1, out
    # past the file-count bound the remainder is handwritten too
    (tmp_path / "two").mkdir()
    top2 = _repo(tmp_path / "two", {"seed.txt": "x\n"})
    n = sc.MAX_HEADER_FILES + 3
    _commit(top2, {f"m/f{i:04d}.py": "# @generated\nx\n" for i in range(n)})
    out2 = sc.measure(str(top2), "origin", "main", {})
    assert out2["files"]["generated_or_mechanical"] == sc.MAX_HEADER_FILES, out2
    assert out2["files"]["handwritten"] == 3


# --- the pr() hook --------------------------------------------------------------------------------

def _pr_fixture(tmp_path, monkeypatch, measured):
    d = tmp_path / ".sdlc"
    (d / "state").mkdir(parents=True)
    (d / "config.json").write_text(json.dumps({"work": {"enabled": True}}))
    wt = tmp_path / ".sdlc" / "work" / "0001-x"
    wt.mkdir(parents=True)
    work._save(str(d), "0001-x.md", {"worktree": str(wt), "branch": "sdlc/0001-x", "base": "main",
                                      "remote": "origin", "pr": ""})
    real = work._load

    class Stub:
        @staticmethod
        def measure(top, remote, base, cfg=None):
            if isinstance(measured, Exception):
                raise measured
            return measured

        soft_cap_note = staticmethod(sc.soft_cap_note)

    monkeypatch.setattr(work, "_load", lambda name: Stub if name == "size_class" else real(name))

    def run(cwd, argv):
        line = " ".join(str(a) for a in argv)
        return {"rev-list": "2", "pulls?head=": "9"}.get(next((k for k in ("rev-list", "pulls?head=") if k in line), ""), "")

    return str(d), run


SIZE = {"files": {c: 0 for c in sc.CLASSES}, "lines": {c: 0 for c in sc.CLASSES}, "cap": 400,
        "over_cap": False}


def test_pr_records_size_and_keeps_the_result_prefix(tmp_path, monkeypatch):
    d, run = _pr_fixture(tmp_path, monkeypatch, SIZE)
    assert work.pr(d, {"work": {"enabled": True}}, "0001-x.md", run=run) == "PR #9"
    assert work._record(d, "0001-x.md").get("size") == SIZE
    d2, run2 = _pr_fixture(tmp_path / "o", monkeypatch, dict(SIZE, over_cap=True, lines=dict(SIZE["lines"], handwritten=500)))
    out = work.pr(d2, {"work": {"enabled": True}}, "0001-x.md", run=run2)
    assert out.startswith("PR #9") and "soft cap" in out and "500" in out


def test_pr_stays_fail_open_when_measuring_fails(tmp_path, monkeypatch):
    d, run = _pr_fixture(tmp_path, monkeypatch, RuntimeError("boom"))
    assert work.pr(d, {"work": {"enabled": True}}, "0001-x.md", run=run) == "PR #9"
    assert "size" not in work._record(d, "0001-x.md")
    d2, run2 = _pr_fixture(tmp_path / "n", monkeypatch, None)
    assert work.pr(d2, {"work": {"enabled": True}}, "0001-x.md", run=run2) == "PR #9"
