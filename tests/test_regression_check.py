def _strip(rec, section, drop_phase=None, drop_row=None):
    """A copy of `rec` with exactly the named evidence removed: a whole stream, a phases[] entry, a log row."""
    out = copy.deepcopy(rec)
    if section:
        del out["streams"][section]
    if drop_phase:
        out["phases"] = [p for p in out["phases"] if p["phase"] != drop_phase]
    if drop_row:
        rows = out["streams"]["action_log"]["rows"]
        out["streams"]["action_log"]["rows"] = [r for r in rows if not all(r.get(a) == b for a, b in drop_row.items())]
    return out


def _strings(node):
    if isinstance(node, str):
        yield node
    elif isinstance(node, dict):
        for k, v in node.items():
            yield k
            for s in _strings(v):
                yield s
    elif isinstance(node, list):
        for v in node:
            for s in _strings(v):
                yield s


def test_each_mutation_differs_from_green_by_exactly_one_deletion():
    """Deleting the ONE piece of evidence from green by hand leaves the same tree as the mutated copy
    with that same piece deleted: nothing else moved, nothing was added elsewhere."""
    green = json.loads((FIXDIR / "run-green.json").read_text(encoding="utf-8"))
    cases = {
        "run-drop-verdict.json": dict(section="plan_review_verdict",
                                      drop_row={"kind": "verdict", "phase": "plan_review"}),
        "run-drop-phase-end.json": dict(section=None, drop_phase="review",
                                        drop_row={"kind": "phase", "phase": "review", "state": "end"}),
        "run-drop-marker.json": dict(section="review_evidence"),
    }
    for name, kw in cases.items():
        mut = json.loads((FIXDIR / name).read_text(encoding="utf-8"))
        assert mut != green, name
        a = _strip(green, **kw)
        b = _strip(mut, kw["section"], None, None) if kw.get("drop_row") is None else \
            _strip(mut, kw["section"], kw.get("drop_phase"), kw.get("drop_row"))
        assert a == b, name
