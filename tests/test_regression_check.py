def _run(record, props=PROPS):
    """The documented gesture: python3 evals/regression/check.py <record> <properties.json>."""
    return subprocess.run([sys.executable, str(CHECK), str(record), str(props)],
                          capture_output=True, text=True, timeout=60)


def _write(path, obj):
    path.write_text(json.dumps(obj, sort_keys=True, indent=2) + "\n", encoding="utf-8")
    return path


def _check_rec(tmp_path, rec, props=PROPS):
    return _run(_write(tmp_path / "rec.json", rec), props)


def _words(proc):
    out = {}
    for line in proc.stdout.splitlines():
        m = LINE.match(line)
        if m:
            out[m.group(2)] = (m.group(1), m.group(3))
    return out


def _props_file(tmp_path, *entries):
    return _write(tmp_path / "props.json", {"properties": list(entries)})


def _prop(**over):
    base = {"id": "process.x", "family": "process", "hard": True, "stream": "action_log",
            "check": "log_row", "kinds": ["merged"], "match": {}, "why": "x"}
    base.update(over)
    return base


def _assert_refused(proc):
    assert proc.returncode == 2, (proc.returncode, proc.stdout, proc.stderr)
    assert proc.stdout == ""
    assert "check.py: REFUSED:" in proc.stderr


def _assert_only(proc, pid, word):
    words = _words(proc)
    assert proc.returncode == 1, proc.stdout
    assert words[pid][0] == word, proc.stdout
    others = {k: v[0] for k, v in words.items() if k != pid}
    assert all(v == "PASS" for v in others.values()), proc.stdout


