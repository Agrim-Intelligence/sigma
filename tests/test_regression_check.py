"""`evals/regression/check.py <record> <properties.json>` -- the regression checker (#877, slice 2 of #870).

Every behavioural test runs the DOCUMENTED gesture, exactly this argv and nothing stronger:

    python3 evals/regression/check.py <record> <properties.json>

as a subprocess (`sys.executable`, no extra flag). No test imports a check function to get its
pass/fail verdict; the in-process module is used only for its seam (`INTERNAL`), the way
`test_regression_record.py` does for the builder.

The committed record and the three mutated copies under `evals/regression/fixtures/` are
regenerated by `tests/regression_fixture.py` and byte-compared here, so they cannot rot.
"""
